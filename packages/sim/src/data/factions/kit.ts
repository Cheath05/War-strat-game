export type Kind = keyof typeof KIT;

/** A unit of `faction`: a kind from the kit, with its own touches and its look. */
export function unit(faction: string, id: string, name: string, desc: string, kind: Kind, sprite: SpriteSpec, over: Partial<Stats> = {}): UnitTypeDef {
  const base = KIT[kind] as Stats;
  return { id: `${faction}.${id}`, faction, name, desc, ...base, forms: [...base.forms], ...over, sprite };
}
