import type { CampaignDef, CampaignNode } from '../../campaign/types';

// The five campaigns: each country's road through its famous battles, left to right. Row 0
// is the main road; rows -1 and 1 are side battles (optional) and choices (either one opens
// the way on). Glory is the reward for winning; troops unlock for Glory once a battle is won.

const node = (battle: string, side: number, col: number, row: number, after: string[], glory: number, more: Partial<CampaignNode> = {}): CampaignNode => ({
  battle,
  side,
  col,
  row,
  after,
  glory,
  ...more,
});

